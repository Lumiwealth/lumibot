@pytest.mark.parametrize(
    "page",
    [p for p in hand_written_broker_pages() if p.stem != "brokers.all"],
    ids=lambda p: p.stem,
)
def test_broker_page_has_faq(page):
    text = page.read_text(encoding="utf-8")
    assert len(re.findall(r"^Frequently asked questions$", text, flags=re.M | re.I)) == 1, page.name
    questions = faq_questions(text)
    assert len(questions) >= 5, f"{page.name} has {len(questions)} FAQ questions; need at least 5"
    for question in questions:
        assert question.endswith("?"), f"{page.name}: FAQ heading is not a question: {question!r}"


