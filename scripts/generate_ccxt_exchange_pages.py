def index_block(page_ids, facts_by_id):
    """The toctree of every exchange page, sorted by display name."""
    names = sorted(page_ids, key=lambda i: facts_by_id[i]["name"].lower() if i in facts_by_id else i)
    lines = [INDEX_START, "", ".. toctree::", "   :maxdepth: 1", ""]
    lines += [f"   brokers.ccxt.{i}" for i in names]
    lines += ["", INDEX_END]
    return "\n".join(lines)


def update_index(page_ids, facts_by_id):
    text = INDEX_PAGE.read_text(encoding="utf-8")
    block = index_block(page_ids, facts_by_id)
    if INDEX_START in text:
        start = text.index(INDEX_START)
        end = text.index(INDEX_END, start) + len(INDEX_END)
        text = text[:start] + block + text[end:]
    else:
        old = re.search(r"\.\. toctree::\n   :maxdepth: 1\n\n(   brokers\.ccxt\.[a-z0-9_]+\n)+", text)
        if not old:
            raise SystemExit("could not find the exchange toctree in brokers.ccxt.rst")
        text = text[:old.start()] + block + "\n" + text[old.end():]
    INDEX_PAGE.write_text(text, encoding="utf-8")


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    facts = load("ccxt_exchange_facts.json")
    notes = load("ccxt_exchange_notes.json")["exchanges"]
    affiliates = load("ccxt_exchange_affiliates.json")
    facts_by_id = {fx["id"]: fx for fx in facts["exchanges"]}
    targets = argv or sorted(notes)
    rendered_ids = sorted(notes)
    for exchange_id in targets:
        if exchange_id not in facts_by_id:
            raise SystemExit(f"{exchange_id}: not in the installed CCXT facts")
        if exchange_id not in notes:
            raise SystemExit(f"{exchange_id}: no hand-checked notes yet; refusing to render a template-only page")
        page = render(exchange_id, facts_by_id, notes, affiliates, facts, rendered_ids)
        if "—" in page or "–" in page:
            raise SystemExit(f"{exchange_id}: page contains an em or en dash")
        (DOCSRC / f"brokers.ccxt.{exchange_id}.rst").write_text(page, encoding="utf-8")
    # Keep hand-written exchange pages (for example an exchange that has closed) in the list.
    existing = {p.stem.split("brokers.ccxt.", 1)[1] for p in DOCSRC.glob("brokers.ccxt.*.rst")}
    update_index(sorted(existing), facts_by_id)
    print(f"wrote {len(targets)} pages; index lists {len(existing)}")


if __name__ == "__main__":
    main()
