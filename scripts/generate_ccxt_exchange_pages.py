def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def yes_no(value):
    if value is True:
        return "Yes"
    if value == "emulated":
        return "Yes (emulated by CCXT)"
    if value is False:
        return "No"
    return "Not listed by CCXT"


def heading(text, char):
    return f"{text}\n{char * len(text)}\n"


def bullets(items, indent=""):
    return "\n".join(f"{indent}* {item}" for item in items)


def numbered(items):
    return "\n".join(f"#. {item}" for item in items)


def code(lang, body, indent="   "):
    lines = body.strip("\n").splitlines()
    return f".. code-block:: {lang}\n\n" + "\n".join(f"{indent}{line}" if line else "" for line in lines) + "\n"


def env_prefix(exchange_id):
    return "".join(ch if ch.isalnum() else "_" for ch in exchange_id).upper()


def env_name(exchange_id, credential, notes=None):
    override = ((notes or {}).get("env_names") or {}).get(credential)
    return override or f"{env_prefix(exchange_id)}_{CREDENTIAL_ENV_SUFFIX.get(credential, credential.upper())}"


def class_name(exchange_id, suffix):
    return "".join(part.capitalize() for part in re.split(r"[^a-zA-Z0-9]", exchange_id) if part) + suffix


class Page:
    """Everything one page needs, resolved once from facts plus notes."""

    def __init__(self, exchange_id, facts_by_id, notes, affiliates):
        self.fx = facts_by_id[exchange_id]
        self.nt = notes[exchange_id]
        self.id = exchange_id
        self.name = self.fx["name"]
        # CCXT's required credentials plus any the exchange's own docs need too.
        self.creds = list(self.fx["required_credentials"]) + [
            c for c in self.nt.get("extra_credentials", []) if c not in self.fx["required_credentials"]
        ]
        # Some exchanges accept only limit orders through CCXT.
        self.market_orders = self.fx["methods"].get("createMarketOrder") in (True, "emulated")
        self.wallet = bool(WALLET_CREDENTIALS & set(self.creds))
        self.quote = self.nt.get("quote_symbol", "USDT")
        self.base = self.nt.get("example_base", "BTC")
        self.notional = self.nt.get("example_notional", 50)
        self.perp_symbol = None if self.fx["markets"].get("spot") else self.nt.get("example_symbol")
        self.sandbox_env = self.nt.get("sandbox_env", f"{env_prefix(exchange_id)}_SANDBOX")
        # A testnet is offered only when CCXT lists one AND the exchange's own
        # docs (the hand-checked note) confirm it.
        self.sandbox = bool(self.fx["sandbox"] and self.sandbox_env and "_SANDBOX=true" in self.nt["testnet_note"])
        self.broker_name = f"ccxt:{exchange_id}" if exchange_id in NATIVE_BROKER_NAMES else exchange_id
        aff = affiliates["exchanges"].get(exchange_id, {})
        self.referral = (aff.get("referral_url") or "").strip()
        self.signup_url = self.referral or self.nt.get("signup_url") or self.fx["urls"]["www"]
        self.disclosure = affiliates["disclosure"]

    def env(self, credential):
        return env_name(self.id, credential, self.nt)


def config_block(p):
    var = env_prefix(p.id)
    lines = ["import os", "", f"{var}_CONFIG = {{", f'    "exchange_id": "{p.id}",']
    for credential in p.creds:
        lines.append(f'    "{credential}": os.environ.get("{p.env(credential)}"),')
    if p.sandbox:
        lines.append('    "sandbox": True,  # testnet first; set False for your live account')
    else:
        lines.append('    "sandbox": False,  # no sandbox for this exchange')
    lines.append("}")
    return "\n".join(lines)


def env_block(p):
    """The .env lines LumiBot reads when TRADING_BROKER is a CCXT exchange id."""
    lines = [f"TRADING_BROKER={p.broker_name}"]
    lines += [f"{p.env(c)}=your_{c}" for c in p.creds]
    if p.sandbox:
        lines.append(f"{p.sandbox_env}=true   # testnet; remove this line for your live account")
    return "\n".join(lines)


def main_block(cls, quote):
    return f'''if __name__ == "__main__":
    # LumiBot reads TRADING_BROKER and the keys from your .env file.
    strategy = {cls}(quote_asset=Asset("{quote}", asset_type=Asset.AssetType.CRYPTO))
    strategy.run_live()
'''


def order_line(p, asset_var, extra):
    """A market buy, or a limit buy just above the last price on limit-only exchanges."""
    args = [asset_var, "quantity", '"buy"']
    if not p.market_orders:
        args.append("limit_price=price * 1.002")
    if extra:
        args.append(extra)
    line = f"order = self.create_order({', '.join(args)})"
    if not p.market_orders:
        line = "# This exchange takes only limit orders through CCXT.\n            " + line
    return line


def order_sentence(p):
    if p.market_orders:
        return ""
    return (f" {p.name} accepts only limit orders through CCXT, so the example places a limit order just above the "
            "last price.")


def spot_example(p):
    cls = class_name(p.id, "BuyOnce")
    return f'''from lumibot.entities import Asset
from lumibot.strategies import Strategy


class {cls}(Strategy):
    """Buy a small amount of {p.base} once, then hold it."""

    def initialize(self):
        self.sleeptime = "1H"
        self.set_market("24/7")  # crypto trades all day, every day

    def on_trading_iteration(self):
        coin = Asset("{p.base}", asset_type=Asset.AssetType.CRYPTO)
        if self.get_position(coin) is not None:
            return  # already holding {p.base}
        price = self.get_last_price(coin, quote=self.quote_asset)
        if price:
            quantity = round({p.notional} / price, 6)  # about {p.notional} {p.quote} worth
            {order_line(p, "coin", "quote=self.quote_asset")}
            self.submit_order(order)


{main_block(cls, p.quote)}'''


def perp_example(p):
    cls = class_name(p.id, "OpenOneLong")
    settle = p.perp_symbol.split(":", 1)[1] if ":" in p.perp_symbol else p.quote
    inverse = settle == p.perp_symbol.split("/", 1)[0]
    if inverse:
        sizing = (f"# Inverse contract: each contract is worth contract.multiplier {p.quote}.\n"
                  f"            quantity = max(1, round({p.notional} / contract.multiplier))")
    else:
        sizing = (f"# Each contract covers contract.multiplier {p.base}; size the order to about {p.notional} {p.quote}.\n"
                  f"            quantity = round({p.notional} / (price * contract.multiplier), 6)")
    return f'''from lumibot.entities import Asset
from lumibot.strategies import Strategy


class {cls}(Strategy):
    """Open one small long {p.base} perpetual position, then hold it."""

    def initialize(self):
        self.sleeptime = "1H"
        self.set_market("24/7")  # crypto trades all day, every day

    def on_trading_iteration(self):
        # The full CCXT symbol keeps the settlement currency clear.
        contract = self.broker.get_asset("{p.perp_symbol}")
        if self.get_position(contract) is not None:
            return  # already holding the position
        price = self.get_last_price(contract)
        if price:
            {sizing}
            {order_line(p, "contract", None)}
            self.submit_order(order)


{main_block(cls, p.quote)}'''


def agent_example(p):
    cls = class_name(p.id, "AITrader")
    if p.perp_symbol:
        what = (f"You may trade the {p.perp_symbol} perpetual contract (asset_type 'crypto_future'), "
                f"long or short, or stay flat. ")
        task = f"Review recent {p.perp_symbol} prices and your current position, then decide whether to buy, sell or hold."
    else:
        what = (f"You may trade {p.base} and ETH against {p.quote} (asset_type 'crypto', quote_symbol '{p.quote}'), "
                f"or hold cash. ")
        task = (f"Review recent {p.base}/{p.quote} and ETH/{p.quote} prices and your current holdings, "
                f"then decide whether to buy, sell or hold.")
    prompt_lines = [
        f"You manage a small crypto account on {p.name}. ",
        what,
        "Before every order, call account_portfolio, account_positions and ",
        "market_last_price for that exact symbol in the same run. ",
        "Keep each order under 10% of the account value. ",
        "Explain each decision in one short paragraph.",
    ]
    prompt = "\n".join(f"                {json.dumps(line)}" for line in prompt_lines)
    return f'''from lumibot.entities import Asset
from lumibot.strategies import Strategy


class {cls}(Strategy):
    """One AI agent researches the market and places the trades itself."""

    def initialize(self):
        self.sleeptime = "4H"
        self.set_market("24/7")
        self.agents.create(
            name="trader",
            model="openai/gpt-6-luna",
            reasoning_effort="high",
            allow_trading=True,
            system_prompt=(
{prompt}
            ),
        )

    def on_trading_iteration(self):
        self.agents["trader"].run(
            task_prompt={json.dumps(task)},
            context={{"exchange": {json.dumps(p.name)}, "quote": "{p.quote}", "date": self.get_datetime().isoformat()}},
        )


{main_block(cls, p.quote)}'''


def swap_example_page(p):
    """A copy of the page set up for a perpetual example, when the exchange lists spot and swaps."""
    if p.perp_symbol or not (p.fx["markets"].get("spot") and p.fx["markets"].get("swap")):
        return None
    # LumiBot reads contract positions through CCXT's fetchPositions; without it a
    # perpetual position would be invisible to the strategy, so no example.
    if p.fx["methods"].get("fetchPositions") not in (True, "emulated"):
        return None
    swap = copy.copy(p)
    swap.perp_symbol = p.nt.get("perp_example_symbol") or f"{p.base}/{p.quote}:{p.quote}"
    return swap


def fee_note(p):
    """Plain description of the CCXT partner-ID and builder-fee policy for this exchange."""
    rules = PARTNER_RULES.get(p.id, ())
    unremovable = [r.target for r in rules if r.kind == "unremovable"]
    parts = [f"You pay {p.name}'s normal trading fees."]
    if unremovable:
        parts.append(
            f"CCXT, the library underneath, tags {p.name} orders with its own partner ID and adds it again while "
            "signing each request, so LumiBot cannot remove it yet. A partner ID does not change what you pay."
        )
    elif rules:
        parts.append(
            f"CCXT, the library underneath, normally tags {p.name} orders with its own partner ID. LumiBot removes "
            "that tag."
        )
    parts.append("LumiBot may attach its own exchange partner ID" + (" instead" if rules else "")
                 + ". That costs you nothing extra.")
    if p.id in BUILDER_FEE_DEFAULTS:
        parts.append(
            f"CCXT also adds its own extra builder fee on {p.name}, paid by you. LumiBot turns it off. LumiBot never "
            "adds a builder fee unless one is turned on in its settings, and it logs a warning when one is, because "
            "it costs you extra on every order."
        )
    else:
        parts.append("LumiBot never adds an extra builder fee unless one is turned on, and it logs a warning when one is.")
    if p.id in REFERRER_EXCHANGES:
        parts.append(
            f"CCXT also tries to register itself as your {p.name} referrer the first time a wallet connects. "
            "LumiBot skips that step."
        )
    return " ".join(parts)


def related_pages(exchange_id, facts_by_id, rendered_ids, limit=4):
    mine = facts_by_id[exchange_id]["markets"]
    scored = []
    for other in sorted(rendered_ids):
        if other == exchange_id:
            continue
        theirs = facts_by_id[other]["markets"]
        score = sum(1 for k in mine if bool(mine[k]) == bool(theirs.get(k)))
        scored.append((-score, other))
    return [other for _, other in sorted(scored)[:limit]]


def titles(p):
    short = f"{p.name} Trading Bot in Python"
    full = f"{p.name} Trading Bot in Python: AI Agent and Algorithmic Trading with LumiBot"
    return short, full


