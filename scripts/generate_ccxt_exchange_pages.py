#!/usr/bin/env python3
"""Render one documentation page per CCXT exchange.

Inputs (all under ``docsrc/_data/``):

* ``ccxt_exchange_facts.json``: facts read from CCXT metadata by
  ``scripts/generate_ccxt_exchange_facts.py``. Never edited by hand.
* ``ccxt_exchange_notes.json``: hand-checked facts from each exchange's own
  official pages (sign-up steps, API key or wallet steps, permissions, testnet),
  each with its source and date. An exchange is rendered only when it has
  notes, so no page ships with nothing but template text. Exchanges whose
  official pages could not be used are listed under ``skipped`` with the reason.
* ``ccxt_exchange_affiliates.json``: our own referral links. Empty means the
  sign-up link goes to the plain official site. CCXT's ``urls.referral`` links
  are never used.

Output: ``docsrc/brokers.ccxt.<id>.rst`` plus the exchange list inside
``docsrc/brokers.ccxt.rst`` (between the generator markers). These files are
generated; edit the JSON inputs or this template instead of the pages.

Rules baked into the template (Rob, 2026-10-23): plain English, no em dashes,
no profit claims, no country or region labels, no "tested by us" or
"community supported" labels. The on-page H1 is short for phones; the full
search title goes in the HTML title through the ``:seo_title:`` field.

Usage::

    python scripts/generate_ccxt_exchange_pages.py            # every exchange with notes
    python scripts/generate_ccxt_exchange_pages.py phemex bybit
"""

