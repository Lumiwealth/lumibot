"""Every hand-written broker page carries an FAQ and the shared BotSpot MCP callout.

Why: the broker guides are the docs pages people find from search and AI
assistants. Each one should answer the common questions in a FAQ (which
docsrc/conf.py turns into FAQPage structured data) and point AI-assistant users
to the BotSpot MCP. Generated CCXT exchange pages are checked by
tests/test_ccxt_exchange_docs.py instead.
"""

import importlib.util
import re
import sys
from pathlib import Path

import pytest
from docutils.core import publish_doctree

ROOT = Path(__file__).resolve().parents[1]
DOCSRC = ROOT / "docsrc"
SNIPPET = DOCSRC / "_snippets" / "botspot_mcp_callout.rst"
INCLUDE = ".. include:: _snippets/botspot_mcp_callout.rst"
GENERATED_MARK = "Generated by scripts/generate_ccxt_exchange_pages.py"
UNDERLINE = re.compile(r"^([=\-~^\"*#+])\1{3,}\s*$")


def _load_docs_config():
    spec = importlib.util.spec_from_file_location("lumibot_docs_conf_faq", DOCSRC / "conf.py")
    module = importlib.util.module_from_spec(spec)
    original_modules = sys.modules.copy()
    try:
        spec.loader.exec_module(module)
    finally:
        for name in set(sys.modules) - set(original_modules):
            sys.modules.pop(name, None)
        sys.modules.update(original_modules)
    return module


def hand_written_broker_pages():
    pages = []
    for page in sorted(DOCSRC.glob("brokers*.rst")):
        if GENERATED_MARK in page.read_text(encoding="utf-8"):
            continue
        pages.append(page)
    return pages


def faq_questions(text):
    """Question headings inside the page's "Frequently asked questions" section."""
    lines = text.splitlines()
    start = None
    for i in range(len(lines) - 1):
        if lines[i].strip().lower() == "frequently asked questions" and UNDERLINE.match(lines[i + 1]):
            start, faq_char = i + 2, lines[i + 1][0]
            break
    if start is None:
        return []
    questions = []
    for i in range(start, len(lines) - 1):
        if lines[i].strip() and UNDERLINE.match(lines[i + 1]):
            if lines[i + 1][0] == faq_char:
                break  # next sibling section ends the FAQ
            questions.append(lines[i].strip())
    return questions


