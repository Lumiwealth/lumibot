def test_faq_extractor_reads_both_question_styles():
    conf = _load_docs_config()
    doctree = publish_doctree(
        "Title\n=====\n\nFrequently asked questions\n--------------------------\n\n"
        "Is it free?\n~~~~~~~~~~~\n\nYes. It is open source.\n\n"
        "Can I backtest?\n~~~~~~~~~~~~~~~\n\nYes.\n",
        settings_overrides={"report_level": 5, "doctitle_xform": False},
    )
    assert conf.extract_faq_pairs(doctree) == [("Is it free?", "Yes. It is open source."), ("Can I backtest?", "Yes.")]
    bold = publish_doctree(
        "Title\n=====\n\nFrequently asked questions\n--------------------------\n\n"
        "**Does it trade?**\n\nYes, live.\n\n**Is there a testnet?**\n\nNo.\n",
        settings_overrides={"report_level": 5, "doctitle_xform": False},
    )
    assert conf.extract_faq_pairs(bold) == [("Does it trade?", "Yes, live."), ("Is there a testnet?", "No.")]
    # faq.rst style: the page itself is the FAQ, with questions grouped under topics.
    grouped = publish_doctree(
        "Frequently Asked Questions (FAQ)\n================================\n\nIntro.\n\n"
        "Getting Started\n---------------\n\nWhat is it?\n~~~~~~~~~~~\n\nA library.\n\n"
        "Brokers\n-------\n\nWhich brokers?\n~~~~~~~~~~~~~~\n\nMany.\n",
        settings_overrides={"report_level": 5, "doctitle_xform": False},
    )
    assert conf.extract_faq_pairs(grouped) == [("What is it?", "A library."), ("Which brokers?", "Many.")]


